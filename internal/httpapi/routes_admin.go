package httpapi

import "github.com/go-chi/chi/v5"

func (s *Server) registerAdminRoutes(r chi.Router) {
	r.With(s.requireInstanceAdmin).Get("/admin/overview", s.adminOverview)
	r.With(s.requireInstanceAdmin).Get("/admin/operations", s.adminOperations)
	r.With(s.requireInstanceAdmin).Get("/admin/audit-events", s.adminAuditEvents)
	r.With(s.requireInstanceAdmin).Get("/admin/telemetry/logs", s.adminTelemetryLogs)
	r.With(s.requireInstanceAdmin).Get("/admin/telemetry/logs/tail", s.adminTelemetryLogTail)
	r.With(s.requireInstanceAdmin).Get("/admin/telemetry/log-volume", s.adminTelemetryLogVolume)
	r.With(s.requireInstanceAdmin).Get("/admin/telemetry/traces", s.adminTelemetryTraces)
	r.With(s.requireInstanceAdmin).Get("/admin/telemetry/metrics", s.adminTelemetryMetrics)
	r.With(s.requireInstanceAdmin).Get("/admin/telemetry/errors", s.adminTelemetryErrors)
	r.With(s.requireInstanceAdmin).Patch("/admin/telemetry/errors/{fingerprint}", s.updateAdminTelemetryErrorStatus)
	r.With(s.requireInstanceAdmin).Get("/admin/telemetry/services", s.adminTelemetryServices)
	r.With(s.requireInstanceAdmin).Get("/admin/infrastructure/metrics", s.adminInfrastructureMetrics)
	r.With(s.requireInstanceAdmin).Get("/admin/telemetry/sources", s.adminTelemetrySources)
	r.With(s.requireInstanceAdmin).Get("/admin/monitors", s.listAdminMonitors)
	r.With(s.requireInstanceAdmin).Post("/admin/monitors", s.createAdminMonitor)
	r.With(s.requireInstanceAdmin).Get("/admin/monitors/{monitorID}", s.getAdminMonitor)
	r.With(s.requireInstanceAdmin).Put("/admin/monitors/{monitorID}", s.updateAdminMonitor)
	r.With(s.requireInstanceAdmin).Delete("/admin/monitors/{monitorID}", s.deleteAdminMonitor)
	r.With(s.requireInstanceAdmin).Get("/admin/alert-events", s.listAdminAlertEvents)
	r.With(s.requireInstanceAdmin).Get("/admin/alerts", s.listAdminAlertRules)
	r.With(s.requireInstanceAdmin).Post("/admin/alerts", s.createAdminAlertRule)
	r.With(s.requireInstanceAdmin).Get("/admin/alerts/{alertRuleID}/events", s.listAdminAlertRuleEvents)
	r.With(s.requireInstanceAdmin).Get("/admin/alerts/{alertRuleID}", s.getAdminAlertRule)
	r.With(s.requireInstanceAdmin).Put("/admin/alerts/{alertRuleID}", s.updateAdminAlertRule)
	r.With(s.requireInstanceAdmin).Delete("/admin/alerts/{alertRuleID}", s.deleteAdminAlertRule)
	r.With(s.requireInstanceAdmin).Get("/admin/notifications", s.listAdminNotificationChannels)
	r.With(s.requireInstanceAdmin).Post("/admin/notifications", s.createAdminNotificationChannel)
	r.With(s.requireInstanceAdmin).Get("/admin/notifications/{channelID}", s.getAdminNotificationChannel)
	r.With(s.requireInstanceAdmin).Put("/admin/notifications/{channelID}", s.updateAdminNotificationChannel)
	r.With(s.requireInstanceAdmin).Post("/admin/notifications/{channelID}/test", s.testAdminNotificationChannel)
	r.With(s.requireInstanceAdmin).Delete("/admin/notifications/{channelID}", s.deleteAdminNotificationChannel)
	r.With(s.requireInstanceAdmin).Get("/admin/incidents", s.listAdminIncidents)
	r.With(s.requireInstanceAdmin).Post("/admin/incidents", s.createAdminIncident)
	r.With(s.requireInstanceAdmin).Get("/admin/incidents/{incidentID}", s.getAdminIncident)
	r.With(s.requireInstanceAdmin).Patch("/admin/incidents/{incidentID}", s.updateAdminIncident)
	r.With(s.requireInstanceAdmin).Post("/admin/incidents/{incidentID}/events", s.addAdminIncidentEvent)
	r.With(s.requireInstanceAdmin).Get("/admin/dashboards", s.listAdminDashboards)
	r.With(s.requireInstanceAdmin).Post("/admin/dashboards", s.createAdminDashboard)
	r.With(s.requireInstanceAdmin).Get("/admin/dashboards/{dashboardID}", s.getAdminDashboard)
	r.With(s.requireInstanceAdmin).Put("/admin/dashboards/{dashboardID}", s.updateAdminDashboard)
	r.With(s.requireInstanceAdmin).Delete("/admin/dashboards/{dashboardID}", s.deleteAdminDashboard)
	r.With(s.requireInstanceAdmin).Get("/admin/status-page", s.getAdminStatusPage)
	r.With(s.requireInstanceAdmin).Put("/admin/status-page", s.updateAdminStatusPage)
}
